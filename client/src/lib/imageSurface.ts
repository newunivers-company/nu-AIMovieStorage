/*
  **그림 위에 무언가를 그리는 화면의 크기 규칙 — 한 벌.**

  탭을 자르기에서 표시하기로 넘기면 같은 그림이 갑자기 커졌습니다 — 화면은 같은데
  크기 규칙만 자리마다 따로 적혀 있었기 때문입니다.

  자르기·표시하기·동선·전개도 6면·파노라마는 **하는 일만 다르고 화면은 같습니다** — 그림 한 장을
  깔고 그 위에 상자·번호·선·자르는 선을 얹습니다. 그런데 크기 규칙이 다섯 군데에 따로 적혀 있어
  (전부 `w-full`) 한 곳만 고치면 탭을 넘기는 순간 그림이 다시 부풀었습니다. 규칙 1 이 말하는
  사고의 모양 그대로입니다 — 「여덟 곳은 맞고 한 곳만 틀리다」.

  그래서 두 가지를 여기 한 벌로 둡니다.

  - `SURFACE_BOX` — 그림을 감싸는 상자. **그림과 딱 같은 크기**여야 합니다. 위에 얹는 것들이
    이 상자를 100% 로 보는 백분율이라, 상자가 그림보다 넓으면 얹은 것이 전부 어긋납니다.
    그래서 `w-fit` 으로 그림에 맞추고 가운데에 놓습니다.
  - `SURFACE_MEDIA` — 그림(또는 캔버스) 자체. **제 크기보다 키우지 않고**(`max-w-full`) 높이도
    창 안에 묶습니다(`max-h`). 1024px 짜리 그림을 1450px 칸에 맞춰 늘이면 세로가 2000px 을 넘어
    아래 띠(저장·닫기)가 화면 밖으로 밀립니다.

  높이 한도를 `62vh` 로 잡은 까닭 — 창 위에 머리줄·탭이, 아래에 저장 띠가 있습니다. 그 둘을 빼고
  남는 만큼입니다. 더 크게 잡으면 띠가 접히고, 더 작게 잡으면 그림이 쓸데없이 작아집니다.
*/

/** 그림을 감싸는 상자. 얹는 것이 백분율이라 그림과 크기가 같아야 합니다. */
export const SURFACE_BOX = "relative mx-auto w-fit select-none";

/** 그림·캔버스 자체. 제 크기 넘게 늘리지 않고, 창 높이 안에 묶습니다. */
export const SURFACE_MEDIA = "block max-h-[62vh] w-auto max-w-full select-none";
